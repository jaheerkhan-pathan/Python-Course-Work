def modulo_division(a,b):
    if b == 0:
        return "division with can't possible"
    return a%b

def floor_division(a,b):
    if b == 0:
        return "division with can't possible"   
    return a//b

def normal_division(a,b):
    if b == 0:
        return "division with can't possible"
    return a/b
